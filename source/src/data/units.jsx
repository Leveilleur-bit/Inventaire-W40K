for (const [old, kept] of Object.entries(UNIT_ALIASES)) { const u = UNIT_BY_ID.get(kept); if (u && !UNIT_BY_ID.has(old)) UNIT_BY_ID.set(old, u); }

// Remplace les anciens identifiants d'unité par celui qui est conservé, partout dans
// l'état : inventaire, reliques mises de côté, Wishlist, liste d'impression, Dé du Destin…
// (toute propriété « unitId ») et dans les points corrigés à la main (ptsMap).
// Les reliques elles-mêmes ne sont pas fusionnées : chacune garde sa fiche et sa photo.
// Sans effet si tout est déjà converti (renvoie alors le même objet).
export function migrateUnitIds(state) {
  if (!state || typeof state !== "object") return state;
  const walk = (v) => {
    if (Array.isArray(v)) {
      let changed = false;
      const out = v.map(x => { const y = walk(x); if (y !== x) changed = true; return y; });
      return changed ? out : v;
    }
    if (v && typeof v === "object" && Object.getPrototypeOf(v) === Object.prototype) {
      let out = null;
      for (const k in v) {
        const x = v[k];
        const y = (k === "unitId" && typeof x === "string" && UNIT_ALIASES[x]) ? UNIT_ALIASES[x] : walk(x);
        if (y !== x) { if (!out) out = { ...v }; out[k] = y; }
      }
      return out || v;
    }
    return v;
  };
  let next = walk(state);
  // Points corrigés à la main : clés « faction:identifiant ». Si les deux exemplaires
  // avaient une correction, celle de l'identifiant conservé l'emporte.
  const pm = next.ptsMap;
  if (pm && typeof pm === "object") {
    let out = null;
    for (const key of Object.keys(pm)) {
      const i = key.indexOf(":"); if (i < 0) continue;
      const kept = UNIT_ALIASES[key.slice(i + 1)]; if (!kept) continue;
      if (!out) out = { ...pm };
      const keptKey = key.slice(0, i + 1) + kept;
      if (out[keptKey] == null) out[keptKey] = pm[key];
      delete out[key];
    }
    if (out) next = { ...next, ptsMap: out };
  }
  return next;
}

